-- =====================================================================
-- GENERA EL SCRIPT DE CREACIÓN DE TODA LA BASE  (solo lee, no cambia nada)
-- Corrélo en Supabase > SQL Editor. Devuelve UNA fila con UNA celda ("script").
-- Copiá esa celda (o "Download CSV") y guardala como  _sql\estructura_AAAA-MM-DD.sql
-- Con ese archivo se pueden volver a crear las tablas, vistas, funciones, índices y triggers
-- (sin datos) en una base vacía. Conviene generarlo de nuevo cada vez que cambie la estructura.
-- Las tablas renombradas a ..._sacar NO se incluyen.
-- =====================================================================
with
-- cada extensión queda en el MISMO esquema que en esta base (algunas funciones lo nombran: ej. f_sin_acentos)
ext as (
    select string_agg(format(
        E'do $e$ begin\n'
        '  if exists (select 1 from pg_extension where extname = %1$L) then\n'
        '    if (select n.nspname from pg_extension e join pg_namespace n on n.oid = e.extnamespace where e.extname = %1$L) <> %2$L then\n'
        '      execute ''alter extension %1$I set schema %2$I'';\n'
        '    end if;\n'
        '  else\n'
        '    execute ''create schema if not exists %2$I'';\n'
        '    execute ''create extension %1$I schema %2$I'';\n'
        '  end if;\n'
        'end $e$;', e.extname, n.nspname), E'\n' order by e.extname) s
    from pg_extension e join pg_namespace n on n.oid = e.extnamespace
    where e.extname not in ('plpgsql', 'pg_graphql', 'pg_stat_statements', 'pgsodium', 'supabase_vault', 'pgjwt')
),
seqs as (
    select string_agg(format('create sequence if not exists public.%I;', c.relname), E'\n' order by c.relname) s
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'S' and c.relname not like '%\_sacar%'
      and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')   -- las de "identity" se crean solas
),
tablas as (
    select string_agg(ddl, E'\n\n' order by nombre) s from (
        select c.relname as nombre,
               format(E'create table if not exists public.%I (\n%s\n);', c.relname,
                   string_agg(
                       format('    %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
                       || case when a.attidentity = 'a' then ' generated always as identity'
                               when a.attidentity = 'd' then ' generated by default as identity' else '' end
                       || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
                               when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end
                       || case when a.attnotnull and a.attidentity = '' then ' not null' else '' end,
                       E',\n' order by a.attnum)) as ddl
        from pg_class c
        join pg_namespace n on n.oid = c.relnamespace
        join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
        left join pg_attrdef ad on ad.adrelid = c.oid and ad.adnum = a.attnum
        where n.nspname = 'public' and c.relkind = 'r' and c.relname not like '%\_sacar'
        group by c.relname
    ) x
),
-- claves primarias, únicas y checks (antes que las FK)
cons as (
    select string_agg(format('alter table public.%I add constraint %I %s;', t.relname, c.conname, pg_get_constraintdef(c.oid)),
                      E'\n' order by case c.contype when 'p' then 1 when 'u' then 2 when 'c' then 3 else 4 end, t.relname, c.conname) s
    from pg_constraint c join pg_class t on t.oid = c.conrelid join pg_namespace n on n.oid = t.relnamespace
    where n.nspname = 'public' and c.contype in ('p', 'u', 'c', 'f') and t.relname not like '%\_sacar'
),
idx as (
    select string_agg(regexp_replace(i.indexdef, '^CREATE (UNIQUE )?INDEX ', 'CREATE \1INDEX IF NOT EXISTS ') || ';', E'\n' order by i.tablename, i.indexname) s
    from pg_indexes i
    where i.schemaname = 'public' and i.tablename not like '%\_sacar'
      and not exists (select 1 from pg_constraint c where c.conname = i.indexname)   -- los de PK/unique ya se crean arriba
),
funcs as (
    select string_agg(pg_get_functiondef(p.oid) || ';', E'\n\n' order by p.proname) s
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind in ('f', 'p')
      and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')   -- no las de extensiones
),
vistas as (
    select string_agg(format(E'create or replace view public.%I as\n%s', c.relname, pg_get_viewdef(c.oid, true)), E'\n\n' order by c.oid) s
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'v'
),
trigs as (
    select string_agg(pg_get_triggerdef(t.oid) || ';', E'\n' order by c.relname, t.tgname) s
    from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and not t.tgisinternal and c.relname not like '%\_sacar'
),
rls as (
    select string_agg(format('alter table public.%I enable row level security;', c.relname), E'\n' order by c.relname) s
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r' and c.relrowsecurity and c.relname not like '%\_sacar'
),
pols as (
    select string_agg(format('create policy %I on public.%I as %s for %s to %s%s%s;',
                             policyname, tablename, permissive, cmd, array_to_string(roles, ', '),
                             coalesce(' using (' || qual || ')', ''), coalesce(' with check (' || with_check || ')', '')),
                      E'\n' order by tablename, policyname) s
    from pg_policies where schemaname = 'public' and tablename not like '%\_sacar'
)
select
    '-- Estructura de la base generada el ' || to_char(now() at time zone 'America/Argentina/Buenos_Aires', 'DD/MM/YYYY HH24:MI') || E'\n'
 || E'-- Correr en una base VACÍA (Supabase > SQL Editor).\n\n'
 || E'set check_function_bodies = off;  -- permite crear las funciones antes que las tablas\n\n'
 || E'-- 1) Extensiones\n'        || coalesce((select s from ext), '')   || E'\n\n'
 || E'-- 2) Secuencias\n'         || coalesce((select s from seqs), '')  || E'\n\n'
 || E'-- 3) Funciones (van antes: algunas columnas calculadas las usan)\n' || coalesce((select s from funcs), '') || E'\n\n'
 || E'-- 4) Tablas\n'             || coalesce((select s from tablas), '')|| E'\n\n'
 || E'-- 5) Claves y reglas\n'    || coalesce((select s from cons), '')  || E'\n\n'
 || E'-- 6) Índices\n'            || coalesce((select s from idx), '')   || E'\n\n'
 || E'-- 7) Vistas\n'             || coalesce((select s from vistas), '')|| E'\n\n'
 || E'-- 8) Triggers\n'           || coalesce((select s from trigs), '') || E'\n\n'
 || E'-- 9) Seguridad (RLS)\n'    || coalesce((select s from rls), '')   || E'\n' || coalesce((select s from pols), '') || E'\n'
 as script;
